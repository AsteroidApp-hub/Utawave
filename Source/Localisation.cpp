void install(Language lang)
{
    const char* table = japaneseTranslations;
    switch (lang)
    {
        case Language::English:            table = englishTranslations;            break;
        case Language::SimplifiedChinese:  table = simplifiedChineseTranslations;  break;
        case Language::TraditionalChinese: table = traditionalChineseTranslations; break;
        case Language::Korean:             table = koreanTranslations;             break;
        case Language::Japanese:
        default:                           table = japaneseTranslations;           break;
    }
    juce::LocalisedStrings::setCurrentMappings(
        new juce::LocalisedStrings(juce::String(juce::CharPointer_UTF8(table)),
                                   /*ignoreCaseOfKeys*/ false));
}

void installJapanese() { install(Language::Japanese); }

static juce::File languageStoreFile()
{
    auto root = juce::File::getSpecialLocation(juce::File::userApplicationDataDirectory)
                    .getChildFile("Utawave");
    root.createDirectory();
    return root.getChildFile("language.txt");
}

Language getSavedLanguage()
{
    auto f = languageStoreFile();
    if (f.existsAsFile())
    {
        // ユーザが明示的に選んだ言語を優先
        const auto txt = f.loadFileAsString().trim().toLowerCase();
        if (txt == "english"  || txt == "en")                     return Language::English;
        if (txt == "japanese" || txt == "ja")                     return Language::Japanese;
        if (txt == "zh-hans"  || txt == "zh-cn" || txt == "zhs")  return Language::SimplifiedChinese;
        if (txt == "zh-hant"  || txt == "zh-tw" || txt == "zht")  return Language::TraditionalChinese;
        if (txt == "korean"   || txt == "ko")                     return Language::Korean;
    }
    // 初回起動 (未保存): システム言語に合わせる。
    const auto sys = juce::SystemStats::getUserLanguage().toLowerCase();
    if (sys.startsWith("ja")) return Language::Japanese;
    if (sys.startsWith("ko")) return Language::Korean;
    if (sys.startsWith("zh"))
    {
        // 繁体圏 (台湾/香港/マカオ) は繁体、それ以外 (中国/シンガポール等) は簡体
        if (sys.contains("hant") || sys.contains("tw") || sys.contains("hk") || sys.contains("mo"))
            return Language::TraditionalChinese;
        return Language::SimplifiedChinese;
    }
    return Language::English;
}

void saveLanguage(Language lang)
{
    const char* code = "japanese";
    switch (lang)
    {
        case Language::English:            code = "english"; break;
        case Language::SimplifiedChinese:  code = "zh-hans"; break;
        case Language::TraditionalChinese: code = "zh-hant"; break;
        case Language::Korean:             code = "korean";  break;
        case Language::Japanese:
        default:                           code = "japanese"; break;
    }
    languageStoreFile().replaceWithText(code);
}

juce::String displayName(Language lang)
{
    switch (lang)
    {
        case Language::English:            return "English";
        case Language::SimplifiedChinese:  return juce::String::fromUTF8(u8"简体中文");
        case Language::TraditionalChinese: return juce::String::fromUTF8(u8"繁體中文");
        case Language::Korean:             return juce::String::fromUTF8(u8"한국어");
        case Language::Japanese:
        default:                           return juce::String::fromUTF8(u8"日本語");
    }
}

